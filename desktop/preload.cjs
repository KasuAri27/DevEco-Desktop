const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("devecoDesktop", {
  getState: (options) => ipcRenderer.invoke("app:get-state", { includeManagement: options?.includeManagement === true }),
  getModelCatalog: () => ipcRenderer.invoke("models:catalog"),
  getWorkspaceSummary: () => ipcRenderer.invoke("workspace:summary"),
  getThemePreference: () => ipcRenderer.invoke("theme:get"),
  setThemePreference: (preference) => ipcRenderer.invoke("theme:set", preference),
  checkProviderConnection: (providerID, apiKey) => ipcRenderer.invoke("provider:check-connection", providerID, apiKey),
  openProviderKeyPage: (providerID) => ipcRenderer.invoke("provider:open-key-page", providerID),
  getSidebar: (options) => ipcRenderer.invoke("sidebar:get", { archived: options?.archived === true }),
  openWorkspace: (directory) => ipcRenderer.invoke("workspace:open", directory),
  openSession: (sessionId, directory) => ipcRenderer.invoke("agent:open-session", sessionId, directory),
  selectWorkspace: () => ipcRenderer.invoke("workspace:select"),
  createSession: () => ipcRenderer.invoke("agent:new-session"),
  archiveSession: (sessionId, directory) => ipcRenderer.invoke("agent:archive-session", sessionId, directory),
  restoreSession: (sessionId, directory) => ipcRenderer.invoke("agent:restore-session", sessionId, directory),
  deleteSession: (sessionId, directory) => ipcRenderer.invoke("agent:delete-session", sessionId, directory),
  reconnectAgent: () => ipcRenderer.invoke("agent:reconnect"),
  sendPrompt: (text) => ipcRenderer.invoke("agent:send", text),
  setConfigOption: (configId, value, type) => ipcRenderer.invoke("agent:set-config-option", configId, value, type),
  setDefaultModel: (model, scope) => ipcRenderer.invoke("agent:set-default-model", model, scope),
  cancelPrompt: () => ipcRenderer.invoke("agent:cancel"),
  respondPermission: (requestId, optionId) => ipcRenderer.invoke("agent:permission-response", requestId, optionId),
  retryManagement: () => ipcRenderer.invoke("management:retry"),
  refreshAccount: () => ipcRenderer.invoke("account:refresh"),
  startHuaweiLogin: () => ipcRenderer.invoke("account:start-login"),
  recheckRealName: () => ipcRenderer.invoke("account:recheck-realname"),
  logoutHuawei: () => ipcRenderer.invoke("account:logout"),
  startOAuth: (providerID, methodIndex, inputs, scope) => ipcRenderer.invoke("oauth:start", providerID, methodIndex, inputs, scope),
  completeOAuth: (flowId, code) => ipcRenderer.invoke("oauth:complete", flowId, code),
  cancelOAuth: (flowId) => ipcRenderer.invoke("oauth:cancel", flowId),
  cancelOAuthProvider: (providerID) => ipcRenderer.invoke("oauth:cancel-provider", providerID),
  getProviders: (scope) => ipcRenderer.invoke("provider:list", scope),
  saveProvider: (input, scope) => ipcRenderer.invoke("provider:save", input, scope),
  removeProvider: (providerID, scope) => ipcRenderer.invoke("provider:remove", providerID, scope),
  removeProviderCredential: (providerID) => ipcRenderer.invoke("provider:remove-credential", providerID),
  refreshProviders: (scope) => ipcRenderer.invoke("provider:refresh", scope),
  getAgreement: () => ipcRenderer.invoke("agreement:get"),
  acceptAgreement: (version, serviceRevision, userAccepted) => ipcRenderer.invoke("agreement:accept", version, serviceRevision, userAccepted),
  getPrivacyPreference: () => ipcRenderer.invoke("privacy:get"),
  setPrivacyPreference: (granted, revision) => ipcRenderer.invoke("privacy:set", granted, revision),
  getDevicePrivacy: () => ipcRenderer.invoke("privacy-device:get"),
  setDevicePrivacy: (preferences, revision) => ipcRenderer.invoke("privacy-device:set", preferences, revision),
  openLegalPage: (url) => ipcRenderer.invoke("legal:open", url),
  openRealNamePage: () => ipcRenderer.invoke("legal:open-realname"),
  getConfig: (scope) => ipcRenderer.invoke("settings:get-config", scope),
  updateConfig: (scope, patch) => ipcRenderer.invoke("settings:update-config", scope, patch),
  selectEnvironmentPath: (kind) => ipcRenderer.invoke("settings:select-path", kind),
  completeOnboarding: () => ipcRenderer.invoke("settings:complete-onboarding"),
  getSetupReadiness: () => ipcRenderer.invoke("setup:readiness"),
  saveProviderCredential: (providerID, apiKey, scope) => ipcRenderer.invoke("provider:save-credential", providerID, apiKey, scope),
  getEnvironment: () => ipcRenderer.invoke("environment:get"),
  checkSignatureCapability: () => ipcRenderer.invoke("environment:check-signature"),
  getDiagnostics: () => ipcRenderer.invoke("diagnostics:get"),
  retryAgent: () => ipcRenderer.invoke("diagnostics:retry-agent"),
  onEvent: (callback) => {
    const listener = (_event, payload) => callback(payload);
    ipcRenderer.on("agent:event", listener);
    return () => ipcRenderer.removeListener("agent:event", listener);
  },
});
